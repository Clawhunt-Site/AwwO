def _safe_skill_name(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9_-]+", "-", value.strip()).strip("-").lower()
    return normalized or "plugin-skill"


def _yaml_scalar(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def render_proxy_skill(manifest: Mapping[str, Any], tool: Mapping[str, Any]) -> str:
    """Render a discovery-only ``SKILL.md`` that routes execution to the proxy.

    B-fast shape: the body names the exact MCP tool and its input schema so the
    runtime can issue a single ``tools/call`` instead of paying the
    ``list_tools`` / ``describe_tool`` round-trips. Execution still lands on the
    SuperClaw MCP proxy and the governance gate.
    """
    plugin_id = str(manifest["id"])
    raw_tool_name = str(tool["name"])
    mcp_tool_name = projected_tool_name(plugin_id, raw_tool_name)
    description = str(tool.get("description") or f"Use SuperClaw plugin tool {raw_tool_name}.")
    input_schema = json.dumps(tool.get("input_schema", {}), indent=2, sort_keys=True, ensure_ascii=False)
    return f"""{MANAGED_MARKER}
---
name: {mcp_tool_name}
description: "{_yaml_scalar(description)}"
---

# {mcp_tool_name}

Use this skill when the task needs the SuperClaw plugin tool `{raw_tool_name}`.

Call the MCP tool `{mcp_tool_name}` through the SuperClaw MCP proxy in one
`tools/call`. Do not load the original plugin directory, sidecar entrypoint,
cache directory, license state, or developer source directly. Every call is
governed by SuperClaw at execution time.

Input schema:

```json
{input_schema}
```
"""


def _tombstone(plugin_id: str) -> str:
    return (
        f"{MANAGED_MARKER}\n"
        "---\n"
        f"name: {_safe_skill_name(plugin_id)}-revoked\n"
        'description: "This SuperClaw skill was revoked and must not be used."\n'
        "---\n\n"
        f"# Revoked\n\nThe SuperClaw skill `{plugin_id}` was revoked. Do not use it.\n"
    )


