# Injected verbatim at the top of every file we generate. Two jobs: it tells a
# human the file is owned by SuperClaw, and it is the marker we look for before
# ever overwriting or deleting a file — no marker means the user owns it and we
# keep our hands off.
MANAGED_MARKER = (
    "<!-- AUTO-GENERATED BY SUPERCLAW — DO NOT EDIT. "
    "Run `superclaw plugin sync-skills` to update; local edits are not synced back. -->"
)

# The projection ledger is user-global because the projection targets are
# user-global (~/.codex/skills, ...). Keeping it in cwd would let lifecycle state
# drift by working directory and orphan files written into the user's home.
DEFAULT_PROJECTION_LOCK = superclaw_home() / "projections.lock"
PROJECTION_LOCK_SCHEMA_VERSION = "0.1.0"
PROXY_TIER = "proxy"
NATIVE_TIER = "native"


def default_projection_lock() -> Path:
    """The projection ledger path, overridable via ``SUPERCLAW_PROJECTION_LOCK``.

    Mirrors how the plugin cache honors ``SUPERCLAW_PLUGIN_CACHE_PATH``: the env
    override lets a surface (API/tests) redirect the ledger without writing into
    the real user home. Resolved at call time so tests can set it after import.
    """
    override = os.environ.get("SUPERCLAW_PROJECTION_LOCK")
    # Call-time under the single data root so it tracks SUPERCLAW_HOME after import.
    return Path(override).expanduser() if override else superclaw_home() / "projections.lock"


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


class SkillSyncError(RuntimeError):
    """Raised when a skill cannot be projected safely."""


# --------------------------------------------------------------------------- #
# Runtime targets (de-hardcoded; absolute env override -> probe -> default)
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class RuntimeSkillTarget:
    """A native runtime's skill directory, resolved without hardcoding a path.

    A runtime's skill directory is a *versioned* fact, not a constant, so
    resolution is layered: an explicit (and absolute) env override always wins;
    otherwise we probe known locations (default first, then alternates a newer
    runtime may have moved to) and use the first that exists; failing that we
    fall back to the default so a first-time sync still creates the canonical
    directory.
    """

    name: str
    env_var: str
    default_subdir: Path
    alternate_subdirs: tuple[Path, ...] = ()

    def skills_dir(
        self,
        *,
        home: Path | None = None,
        env: Mapping[str, str] | None = None,
    ) -> Path:
        environ = os.environ if env is None else env
        override = environ.get(self.env_var)
        if override:
            candidate = Path(override).expanduser()
            if not candidate.is_absolute():
                raise SkillSyncError(f"{self.env_var} must be an absolute path: {override!r}")
            # Normalize away any ``..`` so the override can't traverse out of the
            # directory it names.
            return candidate.resolve()
        base = Path.home() if home is None else home
        for subdir in (self.default_subdir, *self.alternate_subdirs):
            candidate = base / subdir
            if candidate.is_dir():
                return candidate
        return base / self.default_subdir


RUNTIME_TARGETS: dict[str, RuntimeSkillTarget] = {
    "codex": RuntimeSkillTarget(
        name="codex",
        env_var="SUPERCLAW_CODEX_SKILLS_DIR",
        default_subdir=Path(".codex/skills"),
        # Codex has moved its skill path between releases; probe the alternate
        # before falling back so we land in whichever one this version reads.
        alternate_subdirs=(Path(".agents/skills"),),
    ),
    "claude": RuntimeSkillTarget(
        name="claude",
        env_var="SUPERCLAW_CLAUDE_SKILLS_DIR",
        default_subdir=Path(".claude/skills"),
    ),
    "gemini": RuntimeSkillTarget(
        name="gemini",
        env_var="SUPERCLAW_GEMINI_SKILLS_DIR",
        default_subdir=Path(".gemini/skills"),
    ),
}


def resolve_targets(names: tuple[str, ...] | None = None) -> list[RuntimeSkillTarget]:
    """Resolve target names to :class:`RuntimeSkillTarget`; default is all."""
    if names is None:
        return list(RUNTIME_TARGETS.values())
    resolved: list[RuntimeSkillTarget] = []
    for name in names:
        target = RUNTIME_TARGETS.get(name)
        if target is None:
            raise SkillSyncError(
                f"unknown runtime target: {name!r} (known: {', '.join(sorted(RUNTIME_TARGETS))})"
            )
        resolved.append(target)
    return resolved


