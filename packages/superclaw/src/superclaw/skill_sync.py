"""Sync SuperClaw skills into native agent-runtime skill directories.

Why this exists
---------------
Agent runtimes — Codex, Claude Code, Gemini CLI — discover skills by reading
native ``SKILL.md`` directories. SuperClaw therefore needs a managed projection
ledger for two intentionally separate tracks:

- **Native skills** are markdown artifacts imported into
  :mod:`superclaw.skill_store`. Projection copies the normalized ``SKILL.md`` and
  assets in full. Install-time provenance/signature/executable checks live in
  the store; runtime projection adds no plugin governance and no MCP hop.
- **Plugin skills** are the legacy/governed proxy compatibility track. Their
  projected ``SKILL.md`` files remain discovery pointers that call SuperClaw's
  MCP proxy, and enumeration still runs through the fail-closed plugin gate.

Both tracks use the same projection lock for safe reconcile: a user's local edit
is detected and not overwritten, and stale managed files are reclaimed from
positive source-of-truth signals rather than a bare gate miss.
- **Target directories are resolved per runtime, never hardcoded.** A runtime's
  skill path is a versioned fact (Codex has moved between ``.codex/skills`` and
  ``.agents/skills``), so each target resolves via an absolute env override, then
  a probe of known locations, then a default.
- **Every projected file is tracked in a projection lock** under the user's
  global SuperClaw state (the projection targets are user-global, so the ledger
  is too). Writes are atomic and serialized by a file lock; a user's local edit
  is detected (managed marker + render digest) and never silently clobbered.
"""

