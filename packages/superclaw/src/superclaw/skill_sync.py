def _load_manifest(plugin_path: Path) -> dict[str, Any]:
    return json.loads((plugin_path / MANIFEST_NAME).read_text(encoding="utf-8"))


def plan_plugin_skill_sync(
    *,
    plugin_id: str | None = None,
    targets: tuple[str, ...] | None = None,
    cache_root: Path | None = None,
    home: Path | None = None,
    env: Mapping[str, str] | None = None,
    entitlement_file: Path | None = None,
    revocation_file: Path | None = None,
    policy_file: Path | None = None,
    public_key: str | None = None,
    runtime_version: str = DEFAULT_RUNTIME_VERSION,
) -> list[dict[str, Any]]:
    """Compute what a sync would write, without touching the filesystem.

    Enumeration runs through the *same* fail-closed governance gate the call
    path uses (:func:`available_plugins`). A plugin the kernel would not offer
    right now is never projected — so a revoked or unsigned skill cannot leak a
    discovery surface into a runtime.
    """
    return _enumerate_plans(
        plugin_id=plugin_id,
        targets=targets,
        cache_root=cache_root,
        home=home,
        env=env,
        entitlement_file=entitlement_file,
        revocation_file=revocation_file,
        policy_file=policy_file,
        public_key=public_key,
        runtime_version=runtime_version,
    )[0]


def _enumerate_plans(
    *,
    plugin_id: str | None,
    targets: tuple[str, ...] | None,
    cache_root: Path | None,
    home: Path | None,
    env: Mapping[str, str] | None,
    entitlement_file: Path | None,
    revocation_file: Path | None,
    policy_file: Path | None,
    public_key: str | None,
    runtime_version: str,
) -> tuple[list[dict[str, Any]], set[str]]:
    """Return ``(plans, allowed_ids)``.

    ``allowed_ids`` is the set of plugin ids that passed the governance gate this
    run — taken from :func:`available_plugins` directly, *not* reverse-derived
    from the tool plans, so a plugin that enumerated cleanly but now declares no
    tools is still recognized as "allowed" (and its stale projections become
    reclaimable).
    """
    resolved_targets = resolve_targets(targets)
    public_key = public_key or os.environ.get("SUPERCLAW_PLUGIN_ROOT_PUBLIC_KEY")
    # Tools-agnostic gate enumeration: a plugin that passes governance but now
    # declares zero tools must still count as allowed, so its orphaned
    # projections get reclaimed. Same gate as available_plugins (shared code).
    allowed = gate_passing_plugins(
        cache_root=cache_root,
        entitlement_file=entitlement_file,
        revocation_file=revocation_file,
        policy_file=policy_file,
        public_key=public_key,
        runtime_version=runtime_version,
    )
    root = plugin_cache_root(cache_root)
    plans: list[dict[str, Any]] = []
    allowed_ids: set[str] = set()
    for allowed_plugin_id, version in allowed:
        if plugin_id is not None and allowed_plugin_id != plugin_id:
            continue
        plugin_path = root / allowed_plugin_id / version
        try:
            manifest = _load_manifest(plugin_path)
        except (OSError, ValueError):
            continue
        allowed_ids.add(allowed_plugin_id)
        source_digest = str((manifest.get("provenance") or {}).get("package_digest") or "")
        tools = [t for t in manifest.get("tools", []) if isinstance(t, dict) and t.get("name")]
        for target in resolved_targets:
            skills_dir = target.skills_dir(home=home, env=env)
            for tool in tools:
                content = render_proxy_skill(manifest, tool)
                out = skills_dir / _safe_skill_name(f"{allowed_plugin_id}-{tool['name']}") / "SKILL.md"
                plans.append(
                    {
                        "plugin_id": allowed_plugin_id,
                        "version": version,
                        "target": target.name,
                        "tier": PROXY_TIER,
                        "path": str(out),
                        "content": content,
                        "source_digest": source_digest,
                    }
                )
    return plans, allowed_ids


def plan_native_skill_sync(
    *,
    skill_slug: str | None = None,
    targets: tuple[str, ...] | None = None,
    store_dir: Path | None = None,
    home: Path | None = None,
    env: Mapping[str, str] | None = None,
    revocation_file: Path | None = None,
) -> list[dict[str, Any]]:
    """Compute native skill file-copy projections without touching the filesystem.

    Enumeration goes through :func:`superclaw.skill_store.list_skills`, which
    fails closed on a tampered or revoked skill (§5 5b/5c). So a revoked skill is
    never planned — and because it drops out of the desired set, a previously
    projected copy is reclaimed on the next sync.
    """
    plans = _enumerate_native_plans(
        skill_slug=skill_slug,
        targets=targets,
        store_dir=store_dir,
        home=home,
        env=env,
        revocation_file=revocation_file,
    )
    return [{k: v for k, v in plan.items() if k != "content_bytes"} for plan in plans]


def _enumerate_native_plans(
    *,
    skill_slug: str | None,
    targets: tuple[str, ...] | None,
    store_dir: Path | None,
    home: Path | None,
    env: Mapping[str, str] | None,
    revocation_file: Path | None,
) -> list[dict[str, Any]]:
    resolved_targets = resolve_targets(targets)
    # list_skills is the single fail-closed read: it recomputes the on-disk
    # digest and drops any skill that is tampered or revoked, so a revoked skill
    # is excluded from the plan here (never projected) and, being absent from the
    # desired set, its prior projection is reclaimed by _reconcile_native_stale.
    records = list_skills(
        store_dir=store_dir,
        revocation_file=revocation_file or default_skill_revocation_file(),
    )
    plans: list[dict[str, Any]] = []
    for skill in records:
        if skill_slug is not None and skill.slug != skill_slug:
            continue
        for target in resolved_targets:
            target_root = target.skills_dir(home=home, env=env) / skill.slug
            # The SKILL.md slot identifies the skill directory. A pre-existing
            # SKILL.md we never projected (no ledger record) means the whole
            # directory belongs to the user / another tool, so EVERY file of this
            # skill (SKILL.md + assets) is held back — see the directory-atomic
            # foreign guard in sync_native_skills. Carried on each plan so the
            # write loop can decide per (skill, target) without re-resolving dirs.
            skill_md_path = str(target_root / "SKILL.md")
            for source, relative in _native_skill_files(skill):
                out = target_root / relative
                plans.append(
                    {
                        "plugin_id": skill.slug,
                        "version": "",
                        "target": target.name,
                        "tier": NATIVE_TIER,
                        "path": str(out),
                        "skill_md_path": skill_md_path,
                        "content_bytes": source.read_bytes(),
                        "mode": source.stat().st_mode & 0o777,
                        "source_digest": skill.source_digest,
                    }
                )
    return plans


def _native_skill_files(skill: SkillImportRecord) -> list[tuple[Path, Path]]:
    files: list[tuple[Path, Path]] = [(skill.skill_path, Path("SKILL.md"))]
    assets_root = skill.root / "assets"
    if assets_root.exists():
        for path in sorted(item for item in assets_root.rglob("*") if item.is_file()):
            if path.is_symlink():
                raise SkillSyncError(f"native skill asset may not be a symlink: {path}")
            files.append((path, Path("assets") / path.relative_to(assets_root)))
    return files


