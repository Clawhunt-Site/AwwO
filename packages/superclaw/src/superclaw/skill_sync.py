@dataclass
class SyncResult:
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    skipped_local_override: list[str] = field(default_factory=list)
    reclaimed: list[str] = field(default_factory=list)
    tombstoned: list[str] = field(default_factory=list)
    plans: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "written": self.written,
            "unchanged": self.unchanged,
            "skipped_local_override": self.skipped_local_override,
            "reclaimed": self.reclaimed,
            "tombstoned": self.tombstoned,
            "plans": self.plans,
        }


def sync_native_skills(
    *,
    skill_slug: str | None = None,
    targets: tuple[str, ...] | None = None,
    store_dir: Path | None = None,
    home: Path | None = None,
    env: Mapping[str, str] | None = None,
    lock_path: Path | None = None,
    force: bool = False,
    reconcile: bool = True,
    revocation_file: Path | None = None,
    now: Callable[[], datetime] | None = None,
) -> SyncResult:
    """Copy native stored skills into runtime skill directories.

    Native projection is a full-file copy from :mod:`superclaw.skill_store`.
    It does not enumerate plugins, invoke plugin governance, or render MCP proxy
    pointers. Reconcile only touches ledger records with ``tier == "native"``.

    Revocation closes end-to-end (§5 5c): the enumerate step drops a revoked or
    tampered skill, and the reconcile step then reclaims any copy it had
    previously projected into a runtime skill directory.
    """
    clock = now or _utcnow
    lock_path = lock_path if lock_path is not None else default_projection_lock()
    with _hold_lock(lock_path):
        # Plan *inside* the lock so a revocation that lands between planning and
        # writing cannot resurrect a projection another process just withdrew
        # (same discipline as sync_plugin_skills).
        plans = _enumerate_native_plans(
            skill_slug=skill_slug,
            targets=targets,
            store_dir=store_dir,
            home=home,
            env=env,
            revocation_file=revocation_file,
        )
        result = SyncResult(plans=[{k: v for k, v in p.items() if k != "content_bytes"} for p in plans])
        records = load_projection_lock(lock_path)
        desired: set[str] = set()

        # Directory-atomic foreign guard: if a skill's SKILL.md slot already
        # exists but we never projected it (no ledger record), the whole runtime
        # directory belongs to the user / another tool that happens to share the
        # slug. Hold back EVERY file of that skill — not just SKILL.md — so a sync
        # can never inject our asset files into a stranger's same-named skill dir.
        # NOT force-overridable: --force re-asserts OUR projections, it does not
        # license clobbering a directory SuperClaw never created.
        foreign_skill_md: set[str] = {
            plan["skill_md_path"]
            for plan in plans
            if Path(plan["skill_md_path"]).exists() and plan["skill_md_path"] not in records
        }

        for plan in plans:
            path = Path(plan["path"])
            content = plan["content_bytes"]
            render_digest = _digest_bytes(content)
            desired.add(plan["path"])
            existing = records.get(plan["path"])

            # Foreign skill directory (its SKILL.md is not ours): skip the whole
            # skill, even under --force. Report the SKILL.md slot once per skill.
            if plan["skill_md_path"] in foreign_skill_md:
                if plan["path"] == plan["skill_md_path"]:
                    result.skipped_local_override.append(plan["path"])
                continue

            # Foreign individual file (this exact path exists but is unrecorded):
            # never overwrite, even under --force. Force only re-asserts files we
            # have a ledger record for; it does not seize unrelated files.
            if path.exists() and existing is None:
                result.skipped_local_override.append(plan["path"])
                continue

            # Our own projection the user hand-edited: skip unless --force.
            if path.exists() and not force and existing is not None and not _record_is_unmodified(path, existing):
                result.skipped_local_override.append(plan["path"])
                continue

            # Unchanged iff the ON-DISK bytes already equal what we would write.
            # Comparing the file (not just the ledger's recorded digest) is what
            # lets --force actually re-assert a hand-edited projection even when
            # the store content is unchanged — the ledger digest would still match
            # the intended content and wrongly report "unchanged", so force would
            # never restore the file.
            if path.exists() and _file_digest(path) == render_digest:
                result.unchanged.append(plan["path"])
                continue

            _atomic_write_bytes(path, content, mode=plan.get("mode"))
            records[plan["path"]] = ProjectionRecord(
                plugin_id=plan["plugin_id"],
                version=plan["version"],
                target=plan["target"],
                tier=NATIVE_TIER,
                path=plan["path"],
                render_digest=render_digest,
                source_digest=plan["source_digest"],
                synced_at=clock().isoformat(),
            )
            result.written.append(plan["path"])

        if reconcile:
            _reconcile_native_stale(
                records,
                desired=desired,
                scope_skill_slug=skill_slug,
                force=force,
                result=result,
            )

        save_projection_lock(lock_path, records)
    return result


def _reconcile_native_stale(
    records: dict[str, ProjectionRecord],
    *,
    desired: set[str],
    scope_skill_slug: str | None,
    force: bool,
    result: SyncResult,
) -> None:
    for key, record in list(records.items()):
        if record.tier != NATIVE_TIER or key in desired:
            continue
        if scope_skill_slug is not None and record.plugin_id != scope_skill_slug:
            continue
        path = Path(record.path)
        if path.exists() and not force and not _record_is_unmodified(path, record):
            result.skipped_local_override.append(record.path)
            continue
        if path.exists():
            path.unlink()
        _prune_native_empty_parents(path, record.plugin_id)
        records.pop(key, None)
        result.reclaimed.append(record.path)


def native_skill_status(
    *,
    skill_slug: str | None = None,
    targets: tuple[str, ...] | None = None,
    store_dir: Path | None = None,
    home: Path | None = None,
    env: Mapping[str, str] | None = None,
    lock_path: Path | None = None,
    revocation_file: Path | None = None,
) -> list[dict[str, Any]]:
    """Report native-skill projection health WITHOUT writing anything (read-only).

    Surfaces the drift the silent file-copy model would otherwise hide:

    - ``ok`` — projected, on disk, byte-identical to what we projected, and the
      store copy has not changed since.
    - ``not_projected`` — a governed store skill that has not been synced to this
      target yet (the "created != active" gap).
    - ``foreign_collision`` — a same-named SKILL.md occupies the slot that we
      never projected; a sync will hold it back rather than overwrite it.
    - ``drift_local_edit`` — our projection was hand-edited in the runtime dir
      (on-disk bytes differ from the ledger); a sync skips it unless ``--force``.
    - ``drift_store_updated`` — the store skill changed (or grew a file) but the
      projection is stale; re-run sync to refresh it.
    - ``missing_projection`` — the ledger records a projection but the file is
      gone; re-run sync to restore it.
    - ``stale_revoked`` — a projection still on disk whose store skill is now
      revoked/tampered/removed; the next sync reclaims it.

    Ownership is decided at the SKILL.md slot (it identifies the skill directory),
    but the reported status AGGREGATES over EVERY projected file of the skill —
    SKILL.md and each asset — worst-state-first, so an asset-only edit or deletion
    is visible and never masked as ``ok``. Exactly one row per (skill, target).
    """
    resolved_targets = resolve_targets(targets)
    governed = {
        skill.slug: skill
        for skill in list_skills(
            store_dir=store_dir,
            revocation_file=revocation_file or default_skill_revocation_file(),
        )
    }
    records = load_projection_lock(lock_path or default_projection_lock())
    rows: list[dict[str, Any]] = []

    def _emit(slug: str, target_name: str, status: str, detail: str) -> None:
        rows.append({"slug": slug, "target": target_name, "status": status, "detail": detail})

    # Worst-first precedence so one row per (skill, target) reflects the most
    # actionable state across ALL of the skill's files (SKILL.md + every asset),
    # never just SKILL.md — an asset-only edit/deletion must not read as "ok".
    severity = {
        "foreign_collision": 6,
        "not_projected": 5,
        "missing_projection": 4,
        "drift_local_edit": 3,
        "drift_store_updated": 2,
        "ok": 1,
    }

    # 1) Governed store skills × each target.
    for slug, skill in sorted(governed.items()):
        if skill_slug is not None and slug != skill_slug:
            continue
        for target in resolved_targets:
            target_root = target.skills_dir(home=home, env=env) / slug
            skill_md = target_root / "SKILL.md"
            if str(skill_md) not in records:
                # Ownership is decided at the SKILL.md slot (the skill directory).
                if skill_md.exists():
                    _emit(slug, target.name, "foreign_collision", str(skill_md))
                else:
                    _emit(slug, target.name, "not_projected", "run `superclaw skill sync` to project")
                continue
            # Aggregate over EVERY projected file of this skill — SKILL.md and
            # each asset — so asset drift is visible and status matches what sync
            # would actually do.
            status = "ok"
            detail = str(skill_md)
            for _source, relative in _native_skill_files(skill):
                out = target_root / relative
                rec = records.get(str(out))
                if rec is None and out.exists():
                    # An unrecorded file already sits at this asset slot — sync
                    # will hold it back (foreign), so "re-sync" would be a lie.
                    file_status, file_detail = "drift_local_edit", f"unrecorded file at {out}; sync skips it"
                elif rec is None:
                    file_status, file_detail = "drift_store_updated", f"store added {relative}; re-sync"
                elif not out.exists():
                    file_status, file_detail = "missing_projection", str(out)
                elif _file_digest(out) != rec.render_digest:
                    file_status, file_detail = "drift_local_edit", str(out)
                elif rec.source_digest != skill.source_digest:
                    file_status, file_detail = "drift_store_updated", "store changed; re-sync to refresh"
                else:
                    file_status, file_detail = "ok", str(out)
                if severity[file_status] > severity[status]:
                    status, detail = file_status, file_detail
            _emit(slug, target.name, status, detail)

    # 2) Native projections whose store skill is gone (revoked / tampered /
    #    deleted) but a file still lingers — the stale-projection window. Collapse
    #    to one row per (skill, target) even when several asset files remain.
    seen_stale: set[tuple[str, str]] = set()
    target_names = {t.name for t in resolved_targets}
    for _key, record in sorted(records.items()):
        if record.tier != NATIVE_TIER or record.plugin_id in governed:
            continue
        if skill_slug is not None and record.plugin_id != skill_slug:
            continue
        if not Path(record.path).exists():
            continue
        target_name = record.target or ""
        if targets is not None and target_name not in target_names:
            continue
        ident = (record.plugin_id, target_name)
        if ident in seen_stale:
            continue
        seen_stale.add(ident)
        _emit(record.plugin_id, target_name, "stale_revoked", "projection lingers; next sync reclaims it")

    return rows


def _installed_plugin_ids(cache_root: Path | None) -> set[str]:
    return {str(row["id"]) for row in list_cached_plugins(cache_root=cache_root)}


def _revoked_entries(revocation_file: Path | None) -> list[dict[str, Any]]:
    path = revocation_file or default_revocation_file()
    if not path.exists():
        return []
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    return [item for item in payload.get("revoked", []) if isinstance(item, dict) and item.get("plugin_id")]


def _record_is_revoked(record: ProjectionRecord, revoked: list[dict[str, Any]]) -> bool:
    """Match a projection against revocation entries at id+version+digest grain.

    A revocation entry may pin a specific version and/or package digest; an entry
    that omits them revokes the whole plugin id. This mirrors the kernel's own
    revocation check (``PackageTrustVerifier.check_revocation`` /
    ``check_plugin_revocation``) so projection withdrawal can't be coarser (or
    finer) than execution.
    """
    for item in revoked:
        if str(item.get("plugin_id")) != record.plugin_id:
            continue
        version = item.get("version")
        digest = item.get("package_digest")
        if version not in {None, record.version}:
            continue
        if digest not in {None, record.source_digest}:
            continue
        return True
    return False


def sync_plugin_skills(
    *,
    plugin_id: str | None = None,
    targets: tuple[str, ...] | None = None,
    cache_root: Path | None = None,
    home: Path | None = None,
    env: Mapping[str, str] | None = None,
    entitlement_file: Path | None = None,
    revocation_file: Path | None = None,
    policy_file: Path | None = None,
    public_key: str | None = None,
    runtime_version: str = DEFAULT_RUNTIME_VERSION,
    lock_path: Path | None = None,
    force: bool = False,
    reconcile: bool = True,
    now: Callable[[], datetime] | None = None,
) -> SyncResult:
    """Project governed skills into native runtime directories (managed write).

    Only plugins that pass the fail-closed governance gate are projected.
    Idempotent: re-running rewrites only what changed; a user's local edit is
    reported as ``skipped_local_override`` and never overwritten unless
    ``force``. A *full* sync (no ``plugin_id`` filter) also reconciles: it
    reclaims projections for plugins that have since been uninstalled (delete) or
    revoked (tombstone), keyed off positive signals so a misconfigured run can
    never delete everything.
    """
    clock = now or _utcnow
    lock_path = lock_path if lock_path is not None else default_projection_lock()
    with _hold_lock(lock_path):
        # Plan *inside* the lock: governance state (revocations, the cache) can
        # change between planning and writing, so a plan computed before the lock
        # could resurrect a projection another process just revoked.
        plans, allowed_ids = _enumerate_plans(
            plugin_id=plugin_id,
            targets=targets,
            cache_root=cache_root,
            home=home,
            env=env,
            entitlement_file=entitlement_file,
            revocation_file=revocation_file,
            policy_file=policy_file,
            public_key=public_key,
            runtime_version=runtime_version,
        )
        result = SyncResult(plans=[{k: v for k, v in p.items() if k != "content"} for p in plans])
        records = load_projection_lock(lock_path)
        desired: set[str] = set()

        for plan in plans:
            path = Path(plan["path"])
            content = plan["content"]
            render_digest = _digest(content)
            desired.add(plan["path"])
            existing = records.get(plan["path"])

            if path.exists() and not force:
                prior_digest = existing.render_digest if existing else ""
                if not _is_managed_unmodified(path, prior_digest):
                    result.skipped_local_override.append(plan["path"])
                    continue

            if existing is not None and existing.render_digest == render_digest and path.exists():
                result.unchanged.append(plan["path"])
                continue

            _atomic_write(path, content)
            records[plan["path"]] = ProjectionRecord(
                plugin_id=plan["plugin_id"],
                version=plan["version"],
                target=plan["target"],
                tier=plan["tier"],
                path=plan["path"],
                render_digest=render_digest,
                source_digest=plan["source_digest"],
                synced_at=clock().isoformat(),
            )
            result.written.append(plan["path"])

        if reconcile:
            # A scoped sync (a single plugin, e.g. install --sync-skills on an
            # upgrade) reconciles only that plugin's stale records — so a tool
            # removed in the new version is reclaimed — without touching others.
            _reconcile_stale(
                records,
                desired=desired,
                allowed_ids=allowed_ids,
                scope_plugin_id=plugin_id,
                cache_root=cache_root,
                revocation_file=revocation_file,
                force=force,
                result=result,
            )

        save_projection_lock(lock_path, records)
    return result


def _reconcile_stale(
    records: dict[str, ProjectionRecord],
    *,
    desired: set[str],
    allowed_ids: set[str],
    scope_plugin_id: str | None,
    cache_root: Path | None,
    revocation_file: Path | None,
    force: bool,
    result: SyncResult,
) -> None:
    """Reclaim projections that should no longer exist.

    ``scope_plugin_id`` bounds the sweep: ``None`` reconciles every record (a
    full sync), otherwise only records for that plugin (a scoped sync, so other
    plugins' projections are never touched).

    Keyed off *positive* signals only, so a misconfigured sync (e.g. a missing
    public key that empties the allowed set) can never wipe everything:

    - revoked (id+version+digest match) → tombstone;
    - uninstalled (plugin absent from the cache) → delete;
    - a tool that vanished from a plugin we *did* enumerate this run (its id is in
      ``allowed_ids`` but this path was not produced) → delete the stale tool file;
    - a plugin that is installed but was simply not enumerated this run (gate
      miss) → leave untouched.
    """
    installed = _installed_plugin_ids(cache_root)
    revoked = _revoked_entries(revocation_file)
    for key, record in list(records.items()):
        if record.tier != PROXY_TIER:
            continue
        if key in desired:
            continue
        if scope_plugin_id is not None and record.plugin_id != scope_plugin_id:
            continue
        path = Path(record.path)
        guarded_blocked = path.exists() and not force and not _is_managed_unmodified(path, record.render_digest)

        if _record_is_revoked(record, revoked):
            if guarded_blocked:
                result.skipped_local_override.append(record.path)
                continue
            tomb = _tombstone(record.plugin_id)
            _atomic_write(path, tomb)
            records[key] = ProjectionRecord(
                plugin_id=record.plugin_id,
                version=record.version,
                target=record.target,
                tier=record.tier,
                path=record.path,
                render_digest=_digest(tomb),
                source_digest=record.source_digest,
                synced_at=record.synced_at,
            )
            result.tombstoned.append(record.path)
        elif record.plugin_id not in installed or record.plugin_id in allowed_ids:
            # Uninstalled, or a tool that disappeared from a plugin we enumerated
            # cleanly this run. Either way the projection is genuinely stale.
            if guarded_blocked:
                result.skipped_local_override.append(record.path)
                continue
            if path.exists():
                path.unlink()
            _prune_empty_parent(path)
            records.pop(key, None)
            result.reclaimed.append(record.path)


# --------------------------------------------------------------------------- #
# Unsync (explicit reclaim)
# --------------------------------------------------------------------------- #


@dataclass
class UnsyncResult:
    removed: list[str] = field(default_factory=list)
    tombstoned: list[str] = field(default_factory=list)
    skipped_local_override: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "removed": self.removed,
            "tombstoned": self.tombstoned,
            "skipped_local_override": self.skipped_local_override,
        }


def unsync_plugin_skills(
    *,
    plugin_id: str,
    lock_path: Path | None = None,
    revoked: bool = False,
    force: bool = False,
) -> UnsyncResult:
    """Reclaim projected files for a plugin on uninstall / revoke.

    Normal uninstall deletes the managed file; revoke overwrites it with a
    tombstone so a runtime that already discovered the skill sees an explicit
    notice. A user's local override is left untouched (unless ``force``) and
    reported. Proxy-tier skills are already fail-closed at execution time, so a
    missed file never widens what is reachable.
    """
    lock_path = lock_path if lock_path is not None else default_projection_lock()
    with _hold_lock(lock_path):
        records = load_projection_lock(lock_path)
        result = UnsyncResult()
        remaining: dict[str, ProjectionRecord] = {}

        for key, record in records.items():
            if record.tier != PROXY_TIER or record.plugin_id != plugin_id:
                remaining[key] = record
                continue
            path = Path(record.path)
            if path.exists() and not force and not _is_managed_unmodified(path, record.render_digest):
                result.skipped_local_override.append(record.path)
                remaining[key] = record
                continue
            if revoked:
                tomb = _tombstone(plugin_id)
                _atomic_write(path, tomb)
                result.tombstoned.append(record.path)
                remaining[key] = ProjectionRecord(
                    plugin_id=record.plugin_id,
                    version=record.version,
                    target=record.target,
                    tier=record.tier,
                    path=record.path,
                    render_digest=_digest(tomb),
                    source_digest=record.source_digest,
                    synced_at=record.synced_at,
                )
            else:
                if path.exists():
                    path.unlink()
                _prune_empty_parent(path)
                result.removed.append(record.path)

        save_projection_lock(lock_path, remaining)
    return result


def _prune_empty_parent(path: Path) -> None:
    parent = path.parent
    try:
        if parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
    except OSError:
        pass


def _prune_native_empty_parents(path: Path, skill_slug: str) -> None:
    parent = path.parent
    while parent.name != skill_slug:
        try:
            if parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
            else:
                return
        except OSError:
            return
        parent = parent.parent
    try:
        if parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
    except OSError:
        pass
