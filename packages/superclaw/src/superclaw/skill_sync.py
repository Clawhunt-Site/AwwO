@dataclass(frozen=True)
class ProjectionRecord:
    """One projected ``SKILL.md`` file, tracked for update / GC / drift checks."""

    plugin_id: str
    version: str
    target: str
    tier: str
    path: str
    render_digest: str
    source_digest: str
    synced_at: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "plugin_id": self.plugin_id,
            "version": self.version,
            "target": self.target,
            "tier": self.tier,
            "path": self.path,
            "render_digest": self.render_digest,
            "source_digest": self.source_digest,
            "synced_at": self.synced_at,
        }

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "ProjectionRecord":
        return cls(
            plugin_id=str(data["plugin_id"]),
            version=str(data.get("version") or ""),
            target=str(data["target"]),
            tier=str(data.get("tier") or PROXY_TIER),
            path=str(data["path"]),
            render_digest=str(data.get("render_digest") or ""),
            source_digest=str(data.get("source_digest") or ""),
            synced_at=str(data.get("synced_at") or ""),
        )


def load_projection_lock(lock_path: Path) -> dict[str, ProjectionRecord]:
    """Load the projection lock keyed by absolute output path."""
    if not lock_path.exists():
        return {}
    data = json.loads(lock_path.read_text(encoding="utf-8"))
    records: dict[str, ProjectionRecord] = {}
    for entry in data.get("records", []):
        record = ProjectionRecord.from_dict(entry)
        records[record.path] = record
    return records


def save_projection_lock(lock_path: Path, records: Mapping[str, ProjectionRecord]) -> None:
    """Persist the projection lock atomically."""
    payload = {
        "schema_version": PROJECTION_LOCK_SCHEMA_VERSION,
        "records": [records[key].to_dict() for key in sorted(records)],
    }
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write(lock_path, json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n")


@contextlib.contextmanager
def _hold_lock(lock_path: Path) -> Iterator[None]:
    """Serialize the lock's read-modify-write across concurrent CLI invocations.

    Uses ``fcntl`` (POSIX) or ``msvcrt`` (Windows). If neither is available we
    fail closed rather than write the ledger unlocked — a silent no-op would let
    concurrent syncs corrupt the projection record.
    """
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    guard = lock_path.with_name(lock_path.name + ".guard")
    handle = open(guard, "a+")  # noqa: SIM115 - released in finally
    try:
        if fcntl is not None:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        elif msvcrt is not None:  # pragma: no cover - platform dependent
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_LOCK, 1)
        else:  # pragma: no cover - platform dependent
            raise SkillSyncError("no file-locking primitive available; refusing unlocked projection write")
        yield
    finally:
        with contextlib.suppress(OSError):
            if fcntl is not None:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
            elif msvcrt is not None:  # pragma: no cover - platform dependent
                handle.seek(0)
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
        handle.close()


def _digest(content: str) -> str:
    return "sha256:" + hashlib.sha256(content.encode("utf-8")).hexdigest()


def _digest_bytes(content: bytes) -> str:
    return "sha256:" + hashlib.sha256(content).hexdigest()


def _file_digest(path: Path) -> str:
    return _digest_bytes(path.read_bytes())


def _atomic_write(path: Path, content: str) -> None:
    _atomic_write_bytes(path, content.encode("utf-8"))


def _atomic_write_bytes(path: Path, content: bytes, *, mode: int | None = None) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Unique temp in the same directory so concurrent writers never collide and
    # the final replace() stays atomic on one filesystem.
    fd, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=path.name + ".", suffix=".superclaw-tmp")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        if mode is not None:
            tmp.chmod(mode)
        tmp.replace(path)
    finally:
        if tmp.exists():
            tmp.unlink()


def _is_managed_unmodified(path: Path, render_digest: str) -> bool:
    """True iff the on-disk file is ours and untouched since we wrote it.

    The safety gate before any overwrite or delete: a file that lost its marker,
    or whose digest no longer matches what we recorded, was edited by the user (a
    local override) and is never silently clobbered.
    """
    if not path.exists():
        return False
    current = path.read_text(encoding="utf-8", errors="replace")
    if MANAGED_MARKER not in current:
        return False
    return _digest(current) == render_digest


def _record_is_unmodified(path: Path, record: ProjectionRecord | None) -> bool:
    if record is None or not path.exists():
        return False
    if record.tier == NATIVE_TIER:
        return _file_digest(path) == record.render_digest
    return _is_managed_unmodified(path, record.render_digest)


