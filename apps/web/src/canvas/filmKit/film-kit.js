// Light sweep: a soft band of light crosses a surface (a product, a card, a title) once, k 0 -> 1. clip(g) draws the
// surface's path; angle in degrees from vertical; width as a share of the surface; strength 0-1.
function lightSweep(g, x, y, w, h, k, o = {}) {
  if (k <= 0 || k >= 1) return;
  const ang = ((o.angle ?? 20) * Math.PI) / 180, band = (o.width ?? 0.25) * w, travel = w + band * 2 + h * Math.tan(ang);
  const cx = x - band + EASE.inOut(k) * travel;
  g.save(); g.beginPath(); if (o.clip) o.clip(g); else g.rect(x, y, w, h); g.clip();
  g.globalCompositeOperation = 'lighter'; g.translate(cx, y + h / 2); g.rotate(ang);
  const gr = g.createLinearGradient(-band / 2, 0, band / 2, 0), c = o.color ?? '255,248,235', a = o.strength ?? 0.55;
  gr.addColorStop(0, `rgba(${c},0)`); gr.addColorStop(0.5, `rgba(${c},${a})`); gr.addColorStop(1, `rgba(${c},0)`);
  g.fillStyle = gr; g.fillRect(-band / 2, -h * 2, band, h * 4); g.restore();
}
