const buffer = () => { const c = Object.assign(document.createElement('canvas'), { width: W, height: H }); return { c, g: c.getContext('2d', { alpha: false }) }; };
let bufA, bufB, bufSub, bufOut;              // AwwO: made at boot, at the film's size
function drawScene(ctx, sc, t) {
  ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.globalAlpha = 1; ctx.filter = 'none';
  ctx.fillStyle = PALETTE.bg; ctx.fillRect(0, 0, W, H);
  ctx.save(); sc.draw(ctx, clamp((t - sc.from) / (sc.to - sc.from)), t, S); ctx.restore();
}
const sceneAt = (t) => SCENES.find((s) => t >= s.from && t < s.to) ?? SCENES[SCENES.length - 1];
function drawFilm(ctx, t) {                    // the picture at film time t: one scene, or a transition window
  ctx.setTransform(1, 0, 0, 1, 0, 0); ctx.globalAlpha = 1; ctx.filter = 'none';
  const j = SCENES.findIndex((s, n) => n > 0 && s.in?.dur && TRANSITION[s.in.type] && Math.abs(t - s.from) < s.in.dur / 2);
  if (j > 0) {                                 // inside a transition window centred on the scene's start
    const b = SCENES[j];
    drawScene(bufA.g, SCENES[j - 1], t); drawScene(bufB.g, b, t);
    TRANSITION[b.in.type](ctx, bufA.c, bufB.c, (t - b.from + b.in.dur / 2) / b.in.dur, b.in);
  } else drawScene(ctx, sceneAt(t), t);
}
// Finishing, from FINISH (URL overrides for drafts and tests). The tone curve is a per-channel table (a 1D LUT made
// here, no outside LUT file) applied through an SVG filter.
let SAMPLES = 1, WEAVE = 0, TONE = null;     // AwwO: from FINISH at boot
// Blur only where something moves: the first and last sub-frames are compared at 64 px wide; under STILL (mean
// difference, 0-255) the frame keeps one sharp draw, so a mostly still blur scene costs little render time.
const STILL = 0.6, probe = document.createElement('canvas');
let probeG = null;                           // AwwO: sized at boot
const probeOf = (c) => { probeG.drawImage(c, 0, 0, probe.width, probe.height); return probeG.getImageData(0, 0, probe.width, probe.height).data; };
const probeDiff = (a, b) => { let d = 0; for (let k = 0; k < a.length; k += 4) d += Math.abs(a[k] - b[k]) + Math.abs(a[k + 1] - b[k + 1]) + Math.abs(a[k + 2] - b[k + 2]); return d / (0.75 * a.length); };
function printCurve({ lift, knee, contrast, split }, channel, n = 33) {
  return Array.from({ length: n }, (_, i) => {
    const x = i / (n - 1), y = x <= knee ? x : knee + (1 - knee) * (1 - Math.exp(-(x - knee) / (1 - knee)));
    const s = lerp(y, y * y * (3 - 2 * y), contrast), v = lift + (1 - lift) * s;
    return clamp(v + split * (v - 0.5) * (channel === 'R' ? 1 : channel === 'B' ? -1 : 0)).toFixed(4);
  }).join(' ');
}
function installTone() {                     // AwwO: called at boot
  if (!TONE) return;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute"><filter id="tone"
    color-interpolation-filters="sRGB"><feComponentTransfer>${['R', 'G', 'B'].map((c) =>
    `<feFunc${c} type="table" tableValues="${printCurve(TONE, c)}"/>`).join('')}</feComponentTransfer></filter></svg>`;
  document.body.insertAdjacentHTML('beforeend', svg);
}
function renderFrame(frame, at) {             // AwwO: the renderer's t when it gives one
  const t = at ?? frame / FPS;                 // time comes only from the frame index (or the renderer's t)
  const tp = LOOK.hold < FPS ? Math.floor(t * LOOK.hold + 1e-6) / LOOK.hold : t;   // picture time: on twos, each drawing holds
  const punch = 1;
  const sc = sceneAt(t), n = sc.blur ? SAMPLES : 1, finish = WEAVE || TONE || punch !== 1 || LOOK.grade || LOOK.bloom;
  const target = finish ? bufOut.g : g;
  if (n === 1) drawFilm(target, tp);
  else {                                       // 180° shutter: n sub-frames across the open half, centred on the frame
    const open = (FINISH.shutter?.deg ?? 180) / 360 / FPS;
    const at = (s) => clamp(tp + ((s + 0.5) / n - 0.5) * open, sc.from, sc.to - 1e-6);   // a hard cut never blends
    target.setTransform(1, 0, 0, 1, 0, 0); target.filter = 'none';
    drawFilm(bufSub.g, at(0)); target.globalAlpha = 1; target.drawImage(bufSub.c, 0, 0);
    const first = probeOf(bufSub.c);
    drawFilm(bufSub.g, at(n - 1));
    if (probeDiff(first, probeOf(bufSub.c)) < STILL) drawFilm(target, tp);   // nothing moves: one sharp draw
    else {
      target.globalAlpha = 1 / 2; target.drawImage(bufSub.c, 0, 0);
      for (let s = 1; s < n - 1; s++) {
        drawFilm(bufSub.g, at(s)); target.globalAlpha = 1 / (s + 2); target.drawImage(bufSub.c, 0, 0);
      }
    }
    target.globalAlpha = 1;
  }
  g.setTransform(1, 0, 0, 1, 0, 0); g.globalAlpha = 1; g.filter = 'none';
  if (finish) {                                // gate weave: a seeded sub-pixel drift of the whole frame, new every frame
    const px = WEAVE * S.u / 1080, o = (1 + 3 * px / S.u) * punch;
    const dx = px * (0.6 * (2 * noise1(frame * 0.37 + 11) - 1) + 0.4 * (2 * hash1(frame + 0.17) - 1));
    const dy = 0.7 * px * (0.6 * (2 * noise1(frame * 0.31 + 47) - 1) + 0.4 * (2 * hash1(frame + 0.61) - 1));
    const rect = [dx - W * (o - 1) / 2, dy - H * (o - 1) / 2, W * o, H * o];
    g.filter = [LOOK.grade, TONE && 'url(#tone)'].filter(Boolean).join(' ') || 'none';
    g.drawImage(bufOut.c, ...rect);
    if (LOOK.bloom) {                          // highlights only: darks pushed down before the blur, then added on top
      g.save(); g.globalCompositeOperation = 'lighter'; g.globalAlpha = LOOK.bloom;
      g.filter = `brightness(0.55) contrast(2.4) blur(${(S.u * 0.014).toFixed(1)}px)`; g.drawImage(bufOut.c, ...rect); g.restore();
    }
    g.filter = 'none';
  }
  lookTexture(g, S); vignette(g, S, LOOK.vignette);
  grain(g, S, LOOK.grainHold > 1 ? Math.floor(frame / LOOK.grainHold) : frame, LOOK.grain);
}

