  if (m && +m[1] > 0 && +m[2] > 0) { const r = +m[1] / +m[2]; if (vw / vh > r) w = Math.round(vh * r); else h = Math.round(vw / r); }
  W = w; H = h; S.W = W; S.H = H; S.u = Math.min(W, H);
  FRAMES = Math.max(1, Math.round(FPS * DURATION));
