// Look helpers. shade(hex, light): the colour under a light value (0 shadow, 0.5 the colour itself, 1 lit), banded into
// LOOK.steps for toon looks. inkLine(g, S): strokes the current path with the look's outline (no-op when line is 0),
// the same width on screen inside a plane() or outside it.
function shade(hex, light) {
  let l = clamp(light);
  if (LOOK.steps > 1) l = Math.round(l * (LOOK.steps - 1)) / (LOOK.steps - 1);
  const n = parseInt(hex.slice(1), 16), c = [n >> 16, (n >> 8) & 255, n & 255];
  const m = l < 0.5 ? c.map((v) => v * (0.45 + 1.1 * l)) : c.map((v) => v + (255 - v) * (l - 0.5) * 0.9);
  return `rgb(${m.map((v) => Math.round(clamp(v, 0, 255))).join(',')})`;
}
