// One action's joint angles at progress p (seconds for cycles, 0..1 for jump): limb angles from hanging straight down,
// + forward; elbows and knees bend; bob lifts the body; sq squashes (1 = none).
function actionPose(action, p) {
  const s = Math.sin, P = { la: 0.12, le: 0.15, ra: -0.12, re: 0.15, lh: 0, lk: 0, rh: 0, rk: 0, bob: 0, sq: 1, lean: 0, nod: 0, turn: 0, raise: [0, 0] };
  const cyc = (len) => TAU * p / len;
  if (action === 'idle') { const b = s(cyc(3.6)); P.bob = 0.004 * b; P.sq = 1 + 0.01 * b; }
  else if (action === 'walk' || action === 'run') {
    const run = action === 'run', ph = cyc(run ? 0.56 : 0.92), A = run ? 0.85 : 0.45;
    P.lh = A * s(ph); P.rh = -A * s(ph); P.lk = (run ? 1.3 : 0.6) * Math.max(0, s(ph + 1.6)); P.rk = (run ? 1.3 : 0.6) * Math.max(0, s(ph + 1.6 + Math.PI));
    P.la = -A * 0.9 * s(ph); P.ra = A * 0.9 * s(ph); P.le = P.re = run ? 1.4 : 0.35;
    P.bob = (run ? 0.035 : 0.016) * Math.abs(s(ph)); P.lean = run ? 0.14 : 0.03;
  } else if (action === 'wave') { P.raise = [0, 1]; P.ra = -2.5; P.re = 0.6 + 0.4 * s(cyc(0.42)); }
  else if (action === 'cheer') { const b = Math.abs(s(cyc(0.5))); P.raise = [1, 1]; P.la = -2.8 + 0.15 * b; P.ra = -2.8 + 0.15 * b; P.le = P.re = 0.2; P.bob = 0.03 * b; }
  else if (action === 'point') { P.raise = [0, 0.5]; P.ra = -1.55; P.re = 0.05; }
  else if (action === 'nod') { P.nod = 0.16 * s(cyc(0.5)); }
  else if (action === 'shake') { P.turn = 0.35 * s(cyc(0.45)); }
  else if (action === 'dance') { const ph = cyc(0.5); P.lean = 0.1 * s(ph); P.la = -1.6 + 1.2 * s(ph); P.ra = -1.6 - 1.2 * s(ph); P.raise = [0.6, 0.6]; P.bob = 0.025 * Math.abs(s(ph)); P.lk = P.rk = 0.25 + 0.2 * s(ph * 2); }
  else if (action === 'sit') { P.lh = P.rh = 1.5; P.lk = P.rk = 1.5; P.bob = -0.17; P.la = 0.4; P.ra = 0.3; P.le = P.re = 0.9; }
  else if (action === 'jump') {
    const k = clamp(p);
    if (k < 0.2) { const a = k / 0.2; P.sq = 1 - 0.14 * Math.sin(Math.PI * a / 2); P.lk = P.rk = 0.9 * a; P.lh = P.rh = -0.45 * a; P.la = P.ra = 0.6 * a; }
    else if (k < 0.82) { const a = (k - 0.2) / 0.62; P.bob = 0.34 * Math.sin(Math.PI * a); P.sq = 1 + 0.12 * Math.max(0, 1 - a * 3); P.raise = [1, 1]; P.la = P.ra = -2.6; P.lk = P.rk = 0.5 * a; }
    else { const a = (k - 0.82) / 0.18; P.sq = 1 - 0.12 * Math.sin(Math.PI * a); P.lk = P.rk = 0.8 * Math.sin(Math.PI * a); }
  }
  return P;
}
