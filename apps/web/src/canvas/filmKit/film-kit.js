// Small voices built from oscillators and seeded noise. Every voice takes (ctx, out, start time, ..., gain).
function noiseBuffer(ctx, secs, salt) {
  const b = ctx.createBuffer(1, Math.ceil(secs * ctx.sampleRate), ctx.sampleRate), d = b.getChannelData(0), r = rng(salt);
  for (let i = 0; i < d.length; i++) d[i] = r() * 2 - 1;
  return b;
}
function env(param, t, a, peak, d, end = 0.0001) { param.setValueAtTime(0.0001, t); param.exponentialRampToValueAtTime(peak, t + a); param.exponentialRampToValueAtTime(end, t + a + d); }
function pad(ctx, out, t, dur, freqs, gain) {
  const v = ctx.createGain(), lp = ctx.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = 900;
  v.gain.setValueAtTime(gain, t); v.gain.setValueAtTime(gain, t + dur - 0.6); v.gain.linearRampToValueAtTime(0.0001, t + dur);
  v.connect(lp).connect(out);
  for (const f of freqs) for (const det of [-7, 7]) {
    const o = ctx.createOscillator(); o.type = 'sawtooth'; o.frequency.value = f; o.detune.value = det;
    const p = ctx.createStereoPanner(); p.pan.value = det / 10; o.connect(p).connect(v); o.start(t); o.stop(t + dur);
  }
}
function kick(ctx, out, t, gain) {
  const o = ctx.createOscillator(), v = ctx.createGain();
  o.frequency.setValueAtTime(140, t); o.frequency.exponentialRampToValueAtTime(42, t + 0.18);
  env(v.gain, t, 0.003, gain, 0.35); o.connect(v).connect(out); o.start(t); o.stop(t + 0.4);
}
function tick(ctx, out, t, gain) {
  const s = ctx.createBufferSource(), hp = ctx.createBiquadFilter(), v = ctx.createGain();
  s.buffer = noiseBuffer(ctx, 0.06, Math.round(t * 1000)); hp.type = 'highpass'; hp.frequency.value = 6000;
  env(v.gain, t, 0.001, gain, 0.05); s.connect(hp).connect(v).connect(out); s.start(t);
}
function hit(ctx, out, t, gain) {
  kick(ctx, out, t, gain);
  const s = ctx.createBufferSource(), lp = ctx.createBiquadFilter(), v = ctx.createGain();
  s.buffer = noiseBuffer(ctx, 1.6, 99); lp.type = 'lowpass'; lp.frequency.setValueAtTime(3200, t); lp.frequency.exponentialRampToValueAtTime(200, t + 1.2);
  env(v.gain, t, 0.002, gain * 0.5, 1.4); s.connect(lp).connect(v).connect(out); s.start(t);
}
function riser(ctx, out, t, dur, gain) {
  const s = ctx.createBufferSource(), bp = ctx.createBiquadFilter(), v = ctx.createGain();
  s.buffer = noiseBuffer(ctx, dur, 42); bp.type = 'bandpass'; bp.Q.value = 4;
  bp.frequency.setValueAtTime(300, t); bp.frequency.exponentialRampToValueAtTime(3500, t + dur);
  v.gain.setValueAtTime(0.0001, t); v.gain.exponentialRampToValueAtTime(gain, t + dur - 0.02); v.gain.linearRampToValueAtTime(0, t + dur);
  s.connect(bp).connect(v).connect(out); s.start(t); s.stop(t + dur);
}
// A whoosh into a cut is a low swell, not air: a body under 150 Hz with its 150-300 Hz harmonics (what a phone speaker
// can play) and a faint air layer 26 dB down; it swells, accelerating, to its peak at t + dur / 2 (put that on the cut)
// and is gone 0.25 s later. Use it for the few cuts that carry meaning; the music carries the rest.
function whoosh(ctx, out, t, dur, gain) {
  const peak = t + dur * 0.5, end = peak + 0.3, n = noiseBuffer(ctx, end - t, 77);
  const layer = (type, f, q, g, pan) => {
    const s = ctx.createBufferSource(), fl = ctx.createBiquadFilter(), v = ctx.createGain(), p = ctx.createStereoPanner();
    s.buffer = n; fl.type = type; fl.frequency.value = f; fl.Q.value = q; p.pan.value = pan;
    v.gain.setValueAtTime(0.0001, t); v.gain.exponentialRampToValueAtTime(g * 0.1, t + dur * 0.3);
    v.gain.exponentialRampToValueAtTime(g, peak); v.gain.exponentialRampToValueAtTime(g * 0.1, peak + 0.1);
    v.gain.exponentialRampToValueAtTime(g * 0.01, peak + 0.25); v.gain.linearRampToValueAtTime(0, end);
    s.connect(fl).connect(v).connect(p).connect(out); s.start(t); s.stop(end);
  };
  layer('lowpass', 140, 0.7, gain * 1.6, 0);            // body
  layer('bandpass', 220, 1.2, gain * 0.6, 0);           // its harmonics: the part a phone speaker plays
  layer('bandpass', 2800, 0.8, gain * 0.05, 0.3);       // air, 26 dB down
}
// Air: a real rush of air past the camera (wind, a fast object close by), never the sound of a cut.
function air(ctx, out, t, dur, gain) {
  const s = ctx.createBufferSource(), bp = ctx.createBiquadFilter(), v = ctx.createGain(), p = ctx.createStereoPanner();
  s.buffer = noiseBuffer(ctx, dur, 77); bp.type = 'bandpass'; bp.Q.value = 2;
  bp.frequency.setValueAtTime(400, t); bp.frequency.exponentialRampToValueAtTime(3000, t + dur * 0.5); bp.frequency.exponentialRampToValueAtTime(500, t + dur);
  p.pan.setValueAtTime(-0.8, t); p.pan.linearRampToValueAtTime(0.8, t + dur);
  v.gain.setValueAtTime(0.0001, t); v.gain.exponentialRampToValueAtTime(gain, t + dur * 0.5); v.gain.exponentialRampToValueAtTime(0.0001, t + dur);
  s.connect(bp).connect(v).connect(p).connect(out); s.start(t); s.stop(t + dur);
}
function pluck(ctx, out, t, f, gain) {
  const o = ctx.createOscillator(), v = ctx.createGain(); o.type = 'triangle'; o.frequency.value = f;
  env(v.gain, t, 0.004, gain, 1.2); o.connect(v).connect(out); o.start(t); o.stop(t + 1.3);
}
// A sustained lead that stays easy on the ear: triangle + a little saw, low-passed (<= 2.4 kHz), soft 40 ms attack.
function lead(ctx, out, t, f, dur, gain, cutoff = 2400) {
  const v = ctx.createGain(), lp = ctx.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = cutoff; lp.Q.value = 0.5;
  v.gain.setValueAtTime(0.0001, t); v.gain.linearRampToValueAtTime(gain, t + 0.04);
  v.gain.setValueAtTime(gain, t + Math.max(0.05, dur - 0.15)); v.gain.linearRampToValueAtTime(0.0001, t + dur);
  lp.connect(v).connect(out);
  for (const [type, mix] of [['triangle', 1], ['sawtooth', 0.25]]) {
    const o = ctx.createOscillator(), m = ctx.createGain(); o.type = type; o.frequency.value = f; m.gain.value = mix;
    o.connect(m).connect(lp); o.start(t); o.stop(t + dur);
  }
}
// Foley: short filtered noise bursts for contacts. kind: step (soft, low), tap (hard, small), cloth (long, airy).
function foley(ctx, out, t, kind, gain) {
  const k = { step: [180, 900, 0.09], tap: [900, 3200, 0.03], cloth: [600, 3000, 0.25] }[kind] || [400, 2500, 0.08];
  const s = ctx.createBufferSource(), hp = ctx.createBiquadFilter(), lp = ctx.createBiquadFilter(), v = ctx.createGain();
  s.buffer = noiseBuffer(ctx, k[2] + 0.05, Math.round(t * 997)); hp.type = 'highpass'; hp.frequency.value = k[0];
  lp.type = 'lowpass'; lp.frequency.value = k[1]; env(v.gain, t, 0.002, gain, k[2]);
  s.connect(hp).connect(lp).connect(v).connect(out); s.start(t);
}
// Ambience bed for one scene: looped seeded noise shaped per kind, slow seeded drift, 0.3 s crossfades at the edges.
function ambience(ctx, out, from, to, kind, gain, salt) {
  const k = { room: [60, 450, 0.05], air: [150, 1100, 0.15], water: [300, 2200, 0.6], city: [80, 1300, 0.08] }[kind] || [80, 900, 0.1];
  const a = Math.max(0, from - 0.3), b = Math.min(DURATION, to + 0.3), r = rng(salt);
  const s = ctx.createBufferSource(), hp = ctx.createBiquadFilter(), lp = ctx.createBiquadFilter(), v = ctx.createGain();
  s.buffer = noiseBuffer(ctx, 6, salt); s.loop = true; hp.type = 'highpass'; hp.frequency.value = k[0];
  lp.type = 'lowpass'; lp.frequency.value = k[1];
  v.gain.setValueAtTime(0.0001, a); v.gain.linearRampToValueAtTime(gain, a + 0.3);
  for (let t = a + 0.3; t < b - 0.3; t += 0.5) v.gain.linearRampToValueAtTime(gain * (1 - k[2] * r()), Math.min(b - 0.3, t + 0.5));
  v.gain.linearRampToValueAtTime(0.0001, b);
  s.connect(hp).connect(lp).connect(v).connect(out); s.start(a, r() * 5); s.stop(b);
}
// The shared room: a convolution reverb from a generated, seeded impulse (decaying stereo noise, darkened by tone).
let ROOM_IN = null;
function makeRoom(ctx, out) {
  const n = Math.round(ROOM.secs * ctx.sampleRate), ir = ctx.createBuffer(2, n, ctx.sampleRate);
  for (let c = 0; c < 2; c++) {
    const d = ir.getChannelData(c), r = rng(500 + c);
    for (let i = 0; i < n; i++) d[i] = (r() * 2 - 1) * (1 - i / n) ** ROOM.decay;
  }
  const conv = ctx.createConvolver(), lp = ctx.createBiquadFilter(), ret = ctx.createGain();
  conv.buffer = ir; lp.type = 'lowpass'; lp.frequency.value = ROOM.tone; ret.gain.value = 0.5;
  conv.connect(lp).connect(ret).connect(out);
  return conv;
}
// Send a voice to the room: wet(ctx, out, 0.3) returns a node that feeds the dry bus and the shared reverb.
function wet(ctx, out, amount) {
  const n = ctx.createGain(); n.connect(out);
  if (ROOM_IN && amount > 0) { const s = ctx.createGain(); s.gain.value = amount; n.connect(s).connect(ROOM_IN); }
  return n;
}
function sfx(ctx, out, e) {
  const o = wet(ctx, out, e.wet ?? 0.2);
  if (e.voice === 'hit') hit(ctx, o, e.at, e.gain);
  else if (e.voice === 'whoosh') whoosh(ctx, o, e.at, e.dur ?? 0.7, e.gain);
  else if (e.voice === 'air') air(ctx, o, e.at, e.dur ?? 0.7, e.gain);
  else if (e.voice === 'riser') riser(ctx, o, e.at, e.dur ?? 1.6, e.gain);
  else if (e.voice === 'tick') tick(ctx, o, e.at, e.gain);
  else if (e.voice === 'foley') foley(ctx, o, e.at, e.kind ?? 'tap', e.gain);
  else throw new Error(`SFX: unknown voice ${e.voice}`);
}
// Arrangement helpers. spans(part): [from, to) runs where the part plays, neighbouring sections merged (one voice per
// run). beats(part, every): grid times inside those runs, half-open, so a boundary beat is played once.
function spans(part) {
  const out = [];
  for (const s of ARRANGEMENT) if (s.parts.includes(part)) {
    const last = out[out.length - 1];
    if (last && Math.abs(last[1] - s.from) < 1e-6) last[1] = s.to; else out.push([s.from, s.to]);
  }
  return out;
}
function beats(part, every = 60 / BPM) {
  const out = [];
  for (const [a, b] of spans(part)) for (let n = Math.ceil(a / every - 1e-6); n * every < b - 1e-6; n++) out.push(n * every);
  return out;
}
// ---- Music toolkit (KIT/references/sound.md §8): notes and chords by name, grooves as step patterns, drums and bass
// synthesised here, so a film's music can be any genre, never only a bed and a pluck.
const NOTE_PC = { C: 0, 'C#': 1, Db: 1, D: 2, 'D#': 3, Eb: 3, E: 4, F: 5, 'F#': 6, Gb: 6, G: 7, 'G#': 8, Ab: 8, A: 9, 'A#': 10, Bb: 10, B: 11 };
function midiOfName(name) {
  const m = /^([A-G][#b]?)(-?\d)$/.exec(name);
  if (!m) throw new Error(`note "${name}": use a name like A3, C#4, Eb2`);
  return 12 * (+m[2] + 1) + NOTE_PC[m[1]];
}
const hz = (n) => 440 * 2 ** (((typeof n === 'number' ? n : midiOfName(n)) - 69) / 12);   // hz('A4') = 440, hz(69) = 440
const CHORD = { '': [0, 4, 7], m: [0, 3, 7], 7: [0, 4, 7, 10], maj7: [0, 4, 7, 11], m7: [0, 3, 7, 10], m9: [0, 3, 7, 10, 14],
  9: [0, 4, 7, 10, 14], add9: [0, 4, 7, 14], sus2: [0, 2, 7], sus4: [0, 5, 7], dim: [0, 3, 6], aug: [0, 4, 8], 6: [0, 4, 7, 9],
  m6: [0, 3, 7, 9], 5: [0, 7] };
// chord('Am7', 3): its notes in Hz from octave 3; 'C/E' puts E under it; { open: true } spreads every other note up
function chord(name, octave = 3, o = {}) {
  const m = /^([A-G][#b]?)([a-z0-9]*)(?:\/([A-G][#b]?))?$/.exec(name);
  if (!m || !(m[2] in CHORD)) throw new Error(`chord "${name}": a root and one of ${Object.keys(CHORD).map((q) => q || 'major').join(', ')}`);
  const root = midiOfName(m[1] + octave);
  let notes = CHORD[m[2]].map((i) => root + i);
  if (o.open) notes = notes.map((n, i) => n + (i % 2 ? 12 : 0));
  if (m[3]) notes = [midiOfName(m[3] + (octave - 1)), ...notes];
  return notes.map(hz);
}
// The chord of a progression sounding at time t: one chord per `barsEach` bars from bar `from`, looping.
function chordAt(prog, t, barsEach = 1, from = 0) {
  const n = Math.floor((t - bar(from)) / ((bar(1) - bar(0)) * barsEach) + 1e-6);
  return prog[((n % prog.length) + prog.length) % prog.length];
}
// A groove as steps over one bar, inside the part's spans: 'x' a hit, 'X' an accent, anything else a rest; 16 steps
// usually (8 or 12 work); swing 0..0.3 delays the off steps. Returns [{ t, accent, step }].
function grid(part, pattern, o = {}) {
  const steps = pattern.length, len = bar(1) - bar(0), out = [];
  for (const [a, b] of spans(part)) {
    for (let n = Math.floor((a - BEAT0) / len); bar(n) < b - 1e-6; n++) for (let i = 0; i < steps; i++) {
      const c = pattern[i];
      if (c !== 'x' && c !== 'X') continue;
      const t = bar(n) + (i + (i % 2 ? o.swing || 0 : 0)) * len / steps;
      if (t >= a - 1e-6 && t < b - 1e-6) out.push({ t, accent: c === 'X', step: i });
    }
  }
  return out;
}
function snare(ctx, out, t, gain, o = {}) {           // noise crack + a short tonal body; o.tone in Hz, o.dry = tighter
  const n = ctx.createBufferSource(), bp = ctx.createBiquadFilter(), v = ctx.createGain();
  n.buffer = noiseBuffer(ctx, 0.3, Math.round(t * 977) + 3); bp.type = 'bandpass'; bp.frequency.value = 1900; bp.Q.value = 0.7;
  env(v.gain, t, 0.001, gain, o.dry ? 0.09 : 0.18); n.connect(bp).connect(v).connect(out); n.start(t);
  const b = ctx.createOscillator(), bv = ctx.createGain(); b.frequency.setValueAtTime(o.tone || 190, t); b.frequency.exponentialRampToValueAtTime((o.tone || 190) * 0.7, t + 0.08);
  env(bv.gain, t, 0.001, gain * 0.6, 0.08); b.connect(bv).connect(out); b.start(t); b.stop(t + 0.12);
}
function hat(ctx, out, t, gain, o = {}) {              // closed by default; o.open = a longer, softer ring
  const n = ctx.createBufferSource(), hp = ctx.createBiquadFilter(), v = ctx.createGain();
  n.buffer = noiseBuffer(ctx, 0.5, Math.round(t * 991) + 5); hp.type = 'highpass'; hp.frequency.value = 7200;
  env(v.gain, t, 0.001, gain, o.open ? 0.32 : 0.045); n.connect(hp).connect(v).connect(out); n.start(t);
}
function clap(ctx, out, t, gain) {                    // three quick bursts and a short tail
  for (const [d, g2, len] of [[0, 1, 0.012], [0.011, 0.8, 0.012], [0.022, 1, 0.15]]) {
    const n = ctx.createBufferSource(), bp = ctx.createBiquadFilter(), v = ctx.createGain();
    n.buffer = noiseBuffer(ctx, 0.25, Math.round(t * 983) + d * 1000); bp.type = 'bandpass'; bp.frequency.value = 1250; bp.Q.value = 1.2;
    env(v.gain, t + d, 0.001, gain * g2, len); n.connect(bp).connect(v).connect(out); n.start(t + d);
  }
}
function sub808(ctx, out, t, dur, f, gain, o = {}) {   // an 808 style sub: a sine that may glide in, softly driven
  const os = ctx.createOscillator(), v = ctx.createGain(), sh = ctx.createWaveShaper(), curve = new Float32Array(256);
  for (let i = 0; i < 256; i++) { const x = i / 127.5 - 1; curve[i] = Math.tanh(x * (o.drive || 1.6)); }
  sh.curve = curve; os.frequency.setValueAtTime(f * (o.glideFrom || 1), t); os.frequency.exponentialRampToValueAtTime(f, t + (o.glide || 0.04));
  v.gain.setValueAtTime(0.0001, t); v.gain.exponentialRampToValueAtTime(gain, t + 0.006); v.gain.setValueAtTime(gain, t + dur * 0.6);
  v.gain.exponentialRampToValueAtTime(0.0001, t + dur); os.connect(sh).connect(v).connect(out); os.start(t); os.stop(t + dur + 0.02);
}
function bass(ctx, out, t, dur, f, gain, o = {}) {     // a played bass: saw + square an octave down, a closing filter
  const v = ctx.createGain(), lp = ctx.createBiquadFilter(); lp.type = 'lowpass'; lp.Q.value = o.q || 2;
  const c = o.cutoff || 900; lp.frequency.setValueAtTime(c * 2.2, t); lp.frequency.exponentialRampToValueAtTime(c * 0.5, t + Math.min(dur, 0.35));
  env(v.gain, t, 0.006, gain, dur); lp.connect(v).connect(out);
  for (const [type, mul, g2] of [['sawtooth', 1, 0.7], ['square', 0.5, 0.4]]) {
    const os = ctx.createOscillator(), gv = ctx.createGain(); os.type = type; os.frequency.value = f * mul; gv.gain.value = g2;
    os.connect(gv).connect(lp); os.start(t); os.stop(t + dur + 0.05);
  }
}
function stab(ctx, out, t, dur, freqs, gain, o = {}) {  // a chord stab: detuned saws through a low-pass, short
  const v = ctx.createGain(), lp = ctx.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = o.cutoff || 2200;
  env(v.gain, t, 0.004, gain, dur); lp.connect(v).connect(out);
  for (const f of freqs) for (const det of [-9, 9]) {
    const os = ctx.createOscillator(); os.type = 'sawtooth'; os.frequency.value = f; os.detune.value = det;
    const gv = ctx.createGain(); gv.gain.value = 1 / (freqs.length * 2); os.connect(gv).connect(lp); os.start(t); os.stop(t + dur + 0.05);
  }
}
function checkArrangement() {
  const errs = [];
  ARRANGEMENT.forEach((s, i) => {
    const prev = ARRANGEMENT[i - 1];
    if (s.to <= s.from) errs.push(`${s.section}: ends before it starts`);
    if (!prev && Math.abs(s.from) > 1e-6) errs.push(`${s.section}: the first section starts at 0`);
    if (prev && Math.abs(prev.to - s.from) > 1e-6) errs.push(`${prev.section} → ${s.section}: ${prev.to > s.from ? 'overlap' : 'gap'}`);
    if (new Set(s.parts).size !== s.parts.length) errs.push(`${s.section}: a part is listed twice`);
  });
  const end = ARRANGEMENT[ARRANGEMENT.length - 1];
  if (!end || Math.abs(end.to - DURATION) > 1e-6) errs.push('the last section ends at DURATION');
  if (errs.length) throw new Error('ARRANGEMENT: ' + errs.join('; '));
}

// Music ducks under the narration: depth 0.3 ≈ -10 dB, down 0.15 s before a line, back over 0.4 s after it.
function duck(param, level, lines, depth = 0.3) {
  param.setValueAtTime(level, 0);
  const spans = [];
  for (const { at, dur } of [...lines].sort((a, b) => a.at - b.at)) {
    const last = spans[spans.length - 1];
    if (last && at - 0.15 < last[1] + 0.4) last[1] = Math.max(last[1], at + dur); else spans.push([at, at + dur]);
  }
  for (const [s, e] of spans) {
    param.setValueAtTime(level, Math.max(0, s - 0.15)); param.linearRampToValueAtTime(level * depth, s);
    param.setValueAtTime(level * depth, e); param.linearRampToValueAtTime(level, e + 0.4);
  }
}

