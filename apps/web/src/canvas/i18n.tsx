const CATALOG: Record<UiLocale, Record<CanvasTextKey, string>> = { en: EN, zh: ZH };

export function canvasText(locale: UiLocale, key: CanvasTextKey, values: CanvasTextValues = {}): string {
  return CATALOG[locale][key].replace(/\{(\w+)\}/g, (token, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : token);
}

export type CanvasTranslate = (key: CanvasTextKey, values?: CanvasTextValues) => string;
type LocaleValue = { locale: UiLocale; t: CanvasTranslate };
const LocaleContext = createContext<LocaleValue>({ locale: 'zh', t: (key, values) => canvasText('zh', key, values) });

export function LocaleProvider({ locale, children }: { locale: UiLocale; children: ReactNode }) {
  useLayoutEffect(() => { document.documentElement.lang = localeHtmlLang(locale); }, [locale]);
  const value = useMemo<LocaleValue>(() => ({ locale, t: (key, values) => canvasText(locale, key, values) }), [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useCanvasI18n(): LocaleValue {
  return useContext(LocaleContext);
}
