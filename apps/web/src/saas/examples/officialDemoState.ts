const KEY = 'awwo.official-orbit-state.v1';
const MAX_AGE = 30 * 60 * 1000;
export const OFFICIAL_DEMO_STATE_MESSAGE = 'awwo:official-demo-state';

type OrbitState = { plan: 'Starter' | 'Studio' | 'Scale'; seats: number; billing: 'monthly' | 'yearly' };

function orbitState(value: unknown): OrbitState | undefined {
  if (!value || typeof value !== 'object') return;
  const { plan, seats, billing } = value as Record<string, unknown>;
  if ((plan !== 'Starter' && plan !== 'Studio' && plan !== 'Scale')
    || typeof seats !== 'number' || !Number.isInteger(seats) || seats < 1 || seats > 30
    || (billing !== 'monthly' && billing !== 'yearly')) return;
  return { plan, seats, billing };
}

export function rememberOfficialDemoState(value: unknown): void {
  const state = orbitState(value);
  if (!state) return;
  try { sessionStorage.setItem(KEY, JSON.stringify({ state, at: Date.now() })); } catch { /* Preview controls still work without storage. */ }
}

function readOrbitState(): OrbitState | undefined {
  try {
    const value = JSON.parse(sessionStorage.getItem(KEY) || 'null');
    if (value && typeof value.at === 'number' && value.at <= Date.now() && Date.now() - value.at < MAX_AGE) return orbitState(value.state);
  } catch { /* Ignore unavailable storage and invalid data. */ }
}

/** Curated Orbit controls only. Original generated bytes and provenance remain intact;
 * this preview adapter replays inputs in the opaque sandbox, then reports bounded state.
 * It grants no storage, network, navigation, auth or execution capabilities to the frame. */
export function officialDemoSource(id: string, source: string): string {
  if (id !== 'interaction-page') return source;
  const restored = readOrbitState();
  const adapter = `<script>(() => {
    const restored = ${JSON.stringify(restored || null)};
    if (restored) {
      document.querySelector('[data-plan="' + restored.plan + '"]').click();
      const seats = document.getElementById('headcount-input');
      seats.value = String(restored.seats);
      seats.dispatchEvent(new Event('input', { bubbles: true }));
      document.querySelector('[data-cycle="' + restored.billing + '"]').click();
    }
    const publish = () => parent.postMessage({
      type: '${OFFICIAL_DEMO_STATE_MESSAGE}', id: 'interaction-page',
      state: {
        plan: document.querySelector('[data-plan][aria-checked="true"]').dataset.plan,
        seats: Number(document.getElementById('headcount-input').value),
        billing: document.querySelector('[data-cycle][aria-checked="true"]').dataset.cycle
      }
    }, '*');
    ['click', 'input', 'keydown'].forEach(event => document.addEventListener(event, publish));
  })();</script>`;
  return source.replace(/<\/body>/i, `${adapter}</body>`);
}
