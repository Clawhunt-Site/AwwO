import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const frontendRoot = resolve(here, '..');
const repoRoot = resolve(frontendRoot, '..');
const defaultPython = existsSync(resolve(repoRoot, '.venv/bin/python'))
  ? resolve(repoRoot, '.venv/bin/python')
  : 'python3';
const python = process.env.PYTHON || defaultPython;
const openApiJsonPath = resolve(frontendRoot, 'src/features/studio/api/generated/studio-openapi.json');
const outputPath = resolve(frontendRoot, 'src/features/studio/api/generated/studio-openapi.ts');

function runOpenApiExport() {
  const scriptPath = resolve(repoRoot, 'orchestrator/backend/studio_app/scripts/export_openapi.py');
  const result = spawnSync(python, [scriptPath, openApiJsonPath], {
    cwd: resolve(repoRoot, 'orchestrator/backend'),
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.status !== 0) {
    throw new Error(`OpenAPI export failed:\n${result.stderr || result.stdout}`);
  }
}

function safeName(name) {
  const cleaned = String(name).replace(/[^A-Za-z0-9_$]/g, '_');
  return /^[A-Za-z_$]/.test(cleaned) ? cleaned : `Schema_${cleaned}`;
}

function literal(value) {
  return JSON.stringify(value);
}

function typeFromSchema(schema, schemas, seen = new Set()) {
  if (!schema || typeof schema !== 'object') return 'unknown';
  if (schema.$ref) {
    const name = schema.$ref.split('/').pop();
    return `StudioOpenApiSchemas.${safeName(name)}`;
  }
  if (schema.anyOf || schema.oneOf) {
    return (schema.anyOf || schema.oneOf)
      .map((item) => typeFromSchema(item, schemas, seen))
      .join(' | ');
  }
  if (schema.allOf) {
    return schema.allOf.map((item) => typeFromSchema(item, schemas, seen)).join(' & ');
  }
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((item) => literal(item)).join(' | ') || 'never';
  }
  if (Array.isArray(schema.type)) {
    const variants = schema.type.map((item) => typeFromSchema({ ...schema, type: item }, schemas, seen));
    return Array.from(new Set(variants)).join(' | ') || 'unknown';
  }
  const type = schema.type;
  if (type === 'array') {
    return `Array<${typeFromSchema(schema.items, schemas, seen)}>`;
  }
  if (type === 'object' || schema.properties || schema.additionalProperties) {
    const properties = schema.properties || {};
    const required = new Set(schema.required || []);
    const entries = Object.entries(properties).map(([key, value]) => {
      const optional = required.has(key) ? '' : '?';
      return `  ${literal(key)}${optional}: ${typeFromSchema(value, schemas, seen)};`;
    });
    if (schema.additionalProperties && schema.additionalProperties !== true) {
      entries.push(`  [key: string]: ${typeFromSchema(schema.additionalProperties, schemas, seen)};`);
    } else if (schema.additionalProperties === true && !entries.length) {
      return 'Record<string, unknown>';
    }
    return entries.length ? `{\n${entries.join('\n')}\n}` : 'Record<string, unknown>';
  }
  if (type === 'integer' || type === 'number') return 'number';
  if (type === 'boolean') return 'boolean';
  if (type === 'string') return 'string';
  if (type === 'null') return 'null';
  if (schema.const !== undefined) return literal(schema.const);
  return 'unknown';
}

function emitTypes(schema) {
  const schemas = schema.components?.schemas || {};
  const paths = Object.keys(schema.paths || {}).sort();
  const lines = [
    '/* eslint-disable */',
    '// Auto-generated by scripts/generate-studio-api-types.mjs.',
    '// Do not edit by hand; change FastAPI schemas/routes and regenerate.',
    '',
    'export namespace StudioOpenApiSchemas {',
  ];

  for (const [name, definition] of Object.entries(schemas).sort(([left], [right]) => left.localeCompare(right))) {
    const tsName = safeName(name);
    const tsType = typeFromSchema(definition, schemas);
    if (tsType.startsWith('{\n')) {
      lines.push(`  export interface ${tsName} ${tsType.replaceAll('\n', '\n  ')}`);
    } else {
      lines.push(`  export type ${tsName} = ${tsType};`);
    }
    lines.push('');
  }

  lines.push('}');
  lines.push('');
  lines.push(`export type StudioOpenApiSchemaName = ${Object.keys(schemas).sort().map((name) => literal(name)).join(' | ') || 'never'};`);
  lines.push(`export type StudioOpenApiPath = ${paths.map((path) => literal(path)).join(' | ') || 'never'};`);
  lines.push('');
  lines.push('export const studioOpenApiPaths = [');
  for (const path of paths) lines.push(`  ${literal(path)},`);
  lines.push('] as const;');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

runOpenApiExport();
const schema = JSON.parse(readFileSync(openApiJsonPath, 'utf8'));
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, emitTypes(schema), 'utf8');
console.log(`Generated ${outputPath}`);
