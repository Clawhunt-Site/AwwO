// Reproduce the browser module from the vendored, pinned Unicode database.
// Run with --check to detect stale output without modifying any files.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const version = '17.0.0';
const sourceUrl = `https://www.unicode.org/Public/${version}/ucd/CaseFolding.txt`;
const sourceSha256 = 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183';
const input = new URL(`../data/unicode/${version}/CaseFolding.txt`, import.meta.url);
const output = new URL('../src/unicode-casefold.js', import.meta.url);
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error('Usage: node scripts/generate-unicode-casefold.mjs [--check]');
}
const bytes = readFileSync(input);
if (createHash('sha256').update(bytes).digest('hex') !== sourceSha256) {
  throw new Error('CaseFolding.txt SHA-256 differs from the pinned Unicode source.');
}
const source = bytes.toString('utf8');
if (!source.startsWith(`# CaseFolding-${version}.txt\n`)) {
  throw new Error('Unexpected Unicode data version.');
}

const mappings = new Map();
const statusCounts = { C: 0, F: 0, S: 0, T: 0 };
for (const line of source.split('\n')) {
  const record = line.split('#')[0].trim();
  if (!record) continue;
  const match = /^([0-9A-F]{4,6}); ([CFST]); ([0-9A-F ]+);$/.exec(record);
  if (!match) throw new Error(`Invalid CaseFolding.txt record: ${record}`);
  const [, hex, status, target] = match;
  statusCounts[status]++;
  // Default FULL folding uses C and F, never the alternative S or Turkic T.
  if (status !== 'C' && status !== 'F') continue;
  const codePoint = Number.parseInt(hex, 16);
  if (mappings.has(codePoint)) throw new Error(`Duplicate default mapping: ${hex}`);
  mappings.set(codePoint, target.split(' ').map(value => Number.parseInt(value, 16)));
}

const escapePoint = point => point <= 0xffff
  ? `\\u${point.toString(16).padStart(4, '0')}`
  : `\\u{${point.toString(16)}}`;
const rows = [...mappings].sort(([left], [right]) => left - right)
  .map(([point, targets]) => `  [0x${point.toString(16)}, '${targets.map(escapePoint).join('')}'],`)
  .join('\n');
const generated = `// Generated by scripts/generate-unicode-casefold.mjs; do not edit by hand.
// Unicode ${version} default full case folding: C + F mappings only.
// Source: ${sourceUrl}
// Source SHA-256: ${sourceSha256}
// Unicode data copyright and permission: data/unicode/${version}/LICENSE.txt.
export const UNICODE_CASE_FOLD_VERSION = '${version}';

const mappings = new Map([
${rows}
]);

/**
 * Unicode Default Case Folding, independent of host locale and casing APIs.
 * Expands full mappings, preserves unlisted code points and lone surrogates.
 * Nullish values become the empty string, matching the demo's text coercion.
 * Does not normalize, strip accents, or remove default-ignorable characters.
 * For the search contract, pass String(value ?? '').normalize('NFKC').
 * This composition must not be described as Unicode's NFKC_Casefold operation.
 * @param {unknown} value
 * @returns {string}
 */
export function unicodeCaseFold(value) {
  let result = '';
  for (const character of String(value ?? '')) {
    result += mappings.get(character.codePointAt(0)) ?? character;
  }
  return result;
}
`;

if (args[0] === '--check') {
  if (readFileSync(output, 'utf8') !== generated) {
    throw new Error('Generated module is stale; run node scripts/generate-unicode-casefold.mjs.');
  }
} else {
  writeFileSync(output, generated, 'utf8');
}
console.log(JSON.stringify({ mode: args[0] === '--check' ? 'check' : 'generate',
  unicodeVersion: version, sourceUrl, sourceSha256, mappingCount: mappings.size, statusCounts }));
